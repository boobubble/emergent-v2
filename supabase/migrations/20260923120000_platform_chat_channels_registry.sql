DROP POLICY IF EXISTS "Public read active platform channels" ON public.platform_chat_channels;
CREATE POLICY "Public read active platform channels"
  ON public.platform_chat_channels
  FOR SELECT
  TO anon, authenticated
  USING (enabled AND archived_at IS NULL);

DROP POLICY IF EXISTS "Admins manage platform channels" ON public.platform_chat_channels;
CREATE POLICY "Admins manage platform channels"
  ON public.platform_chat_channels
  FOR ALL
  TO authenticated
  USING (public.is_admin(auth.uid()))
  WITH CHECK (public.is_admin(auth.uid()));

DROP POLICY IF EXISTS "Public read bots for active platform channels" ON public.platform_channel_bots;
CREATE POLICY "Public read bots for active platform channels"
  ON public.platform_channel_bots
  FOR SELECT
  TO anon, authenticated
  USING (
    EXISTS (
      SELECT 1
      FROM public.platform_chat_channels c
      WHERE c.id = platform_channel_bots.channel_id
        AND c.enabled
        AND c.archived_at IS NULL
    )
  );

DROP POLICY IF EXISTS "Admins manage platform channel bots" ON public.platform_channel_bots;
CREATE POLICY "Admins manage platform channel bots"
  ON public.platform_channel_bots
  FOR ALL
  TO authenticated
  USING (public.is_admin(auth.uid()))
  WITH CHECK (public.is_admin(auth.uid()));

