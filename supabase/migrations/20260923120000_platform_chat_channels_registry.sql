-- Phase 3B-1: authoritative platform public channel registry (foundation only).
-- Does NOT modify public.messages, guest chat, presence, typing, or DM/trio policies.

-- ---------------------------------------------------------------------------
-- Permanent channel-number allocator (numbers are never deleted/reused)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.platform_chat_channel_number_alloc (
  channel_number bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);

