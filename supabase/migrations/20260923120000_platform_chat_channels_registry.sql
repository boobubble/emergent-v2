  true
);

-- ---------------------------------------------------------------------------
-- Platform channel registry
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.platform_chat_channels (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  channel_number  bigint NOT NULL,
  slug            text NOT NULL,
  name            text NOT NULL,
  description     text NOT NULL DEFAULT '',
  enabled         boolean NOT NULL DEFAULT true,
  archived_at     timestamptz NULL,
  guest_allowed   boolean NOT NULL DEFAULT false,
  sort_order      integer NOT NULL DEFAULT 0,
  channel_kind    text NOT NULL DEFAULT 'admin'
    CHECK (channel_kind IN ('system', 'admin')),
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT platform_chat_channels_channel_number_key UNIQUE (channel_number),
  CONSTRAINT platform_chat_channels_slug_key UNIQUE (slug),
  CONSTRAINT platform_chat_channels_slug_format_chk
    CHECK (slug ~ '^[a-z0-9][a-z0-9_-]{0,63}$'),
  CONSTRAINT platform_chat_channels_system_slug_chk
    CHECK (channel_kind <> 'system' OR slug IN ('yaarzo-global', 'games')),
  CONSTRAINT platform_chat_channels_archive_state_chk
    CHECK (NOT enabled OR archived_at IS NULL)
);

CREATE INDEX IF NOT EXISTS platform_chat_channels_nav_idx
  ON public.platform_chat_channels (sort_order, channel_number)
  WHERE enabled AND archived_at IS NULL;

-- ---------------------------------------------------------------------------
-- Bot assignments (foundation; runtime bot behavior unchanged in 3B-1)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.platform_channel_bots (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  channel_id  uuid NOT NULL REFERENCES public.platform_chat_channels(id) ON DELETE RESTRICT,
  bot_key     text NOT NULL,
  enabled     boolean NOT NULL DEFAULT true,
  config      jsonb NOT NULL DEFAULT '{}'::jsonb,
  sort_order  integer NOT NULL DEFAULT 0,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT platform_channel_bots_unique UNIQUE (channel_id, bot_key)
);

CREATE INDEX IF NOT EXISTS platform_channel_bots_channel_enabled_idx
  ON public.platform_channel_bots (channel_id)
  WHERE enabled;

-- ---------------------------------------------------------------------------
-- Slug validation (shared by triggers and RPCs)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.is_uuid_text(_value text)
RETURNS boolean
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT _value ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$';
$$;

-- Keep reserved route list aligned with src/lib/reserved-routes.ts (plus chat namespaces).
CREATE OR REPLACE FUNCTION public.is_valid_platform_channel_slug(
  _slug text,
  _channel_kind text DEFAULT 'admin'
)
RETURNS boolean
LANGUAGE plpgsql
STABLE
SET search_path = public
AS $$
DECLARE
  s text := lower(trim(coalesce(_slug, '')));
  kind text := lower(trim(coalesce(_channel_kind, 'admin')));
  reserved_routes text[] := ARRAY[
    'admin','api','feed','games','rooms','chatroom','chatrooms','messages','profile','profiles',
    'settings','friends','find-friends','notifications','login','register','signup','logout','auth',
    'account','achievements','leaderboard','reset-password','welcome','banned','confessions','feedback',
    'u','p','assets','static','public','manifest','robots','sitemap','favicon','root','index','reels',
    'pages','groups','installer','setup-wizard','pricing','wallet','deploy','radio','trust','heropage',
    'community','communities','competitions','battle-hub','broadcaster','gamification','invite',
    'live-arena','dm','trio','gdm','lobby','watch','adm'
  ];
BEGIN
  IF s IS NULL OR s = '' THEN
    RETURN false;
  END IF;
  IF kind NOT IN ('system', 'admin') THEN
    RETURN false;
  END IF;
  IF s IN ('yaarzo-global', 'games') THEN
    RETURN kind = 'system';
  END IF;
  IF kind = 'system' THEN
    RETURN false;
  END IF;
  IF s !~ '^[a-z0-9][a-z0-9_-]{0,63}$' THEN
    RETURN false;
  END IF;
  IF public.is_uuid_text(s) THEN
    RETURN false;
  END IF;
  IF s = 'dm' OR s LIKE 'dm:%' OR s LIKE 'dm-%'
     OR s = 'trio' OR s LIKE 'trio:%' OR s LIKE 'trio-%'
     OR s = 'gdm' OR s LIKE 'gdm:%' OR s LIKE 'gdm-%'
     OR s = 'watch' OR s LIKE 'watch:%' OR s LIKE 'watch-%'
     OR s = 'lobby' THEN
    RETURN false;
  END IF;
  IF s = ANY(reserved_routes) THEN
    RETURN false;
  END IF;
  IF EXISTS (SELECT 1 FROM public.platform_chat_channels c WHERE c.slug = s) THEN
    RETURN false;
  END IF;
  RETURN true;
END;
$$;

-- ---------------------------------------------------------------------------
-- Slug + immutable guards
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.platform_chat_channels_guard_insert()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  IF NOT public.is_valid_platform_channel_slug(NEW.slug, NEW.channel_kind) THEN
    RAISE EXCEPTION 'invalid platform channel slug: %', NEW.slug;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_platform_chat_channels_guard_insert ON public.platform_chat_channels;
CREATE TRIGGER trg_platform_chat_channels_guard_insert
  BEFORE INSERT ON public.platform_chat_channels
  FOR EACH ROW
  EXECUTE FUNCTION public.platform_chat_channels_guard_insert();

CREATE OR REPLACE FUNCTION public.platform_chat_channels_guard_update()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  IF OLD.channel_number IS DISTINCT FROM NEW.channel_number THEN
    RAISE EXCEPTION 'channel_number is immutable';
  END IF;
  IF OLD.slug IS DISTINCT FROM NEW.slug THEN
    RAISE EXCEPTION 'channel slug is immutable';
  END IF;
  IF OLD.channel_kind IS DISTINCT FROM NEW.channel_kind THEN
    RAISE EXCEPTION 'channel_kind is immutable';
  END IF;
  IF OLD.channel_kind = 'system' AND (
    NEW.enabled IS DISTINCT FROM OLD.enabled
    OR NEW.archived_at IS DISTINCT FROM OLD.archived_at
  ) THEN
    RAISE EXCEPTION 'system channels cannot be disabled or archived';
  END IF;
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_platform_chat_channels_guard_update ON public.platform_chat_channels;
CREATE TRIGGER trg_platform_chat_channels_guard_update
  BEFORE UPDATE ON public.platform_chat_channels
  FOR EACH ROW
  EXECUTE FUNCTION public.platform_chat_channels_guard_update();

CREATE OR REPLACE FUNCTION public.platform_chat_channels_guard_delete()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  IF OLD.channel_kind = 'system' THEN
    RAISE EXCEPTION 'system channels cannot be deleted';
  END IF;
  RETURN OLD;
END;
$$;

DROP TRIGGER IF EXISTS trg_platform_chat_channels_guard_delete ON public.platform_chat_channels;
CREATE TRIGGER trg_platform_chat_channels_guard_delete
  BEFORE DELETE ON public.platform_chat_channels
  FOR EACH ROW
  EXECUTE FUNCTION public.platform_chat_channels_guard_delete();

CREATE OR REPLACE FUNCTION public.platform_channel_bots_set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_platform_channel_bots_updated_at ON public.platform_channel_bots;
CREATE TRIGGER trg_platform_channel_bots_updated_at
  BEFORE UPDATE ON public.platform_channel_bots
  FOR EACH ROW
  EXECUTE FUNCTION public.platform_channel_bots_set_updated_at();

